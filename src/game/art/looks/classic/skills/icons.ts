/**
 * Classic's 16 × 16 skill icons, one sheet per `SkillId`, each with a
 * two-frame `idle` glint so the select screen always has something alive.
 */

const SIZE = { w: 16, h: 16 } as const;
const OUTLINE = '#120e24';

function icon(palette: Record<string, string>, frameA: string[], frameB: string[]): PixelArtSheet<SkillIconAnimation> {
  return {
    palette: { o: OUTLINE, ...palette },
    size: SIZE,
    origin: { x: 0, y: 0 },
    animations: { idle: { fps: 3, loop: true, frames: [frameA, frameB] } },
  };
}

